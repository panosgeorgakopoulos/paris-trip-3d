export const LAT0 = 48.8640;
export const LON0 = 2.3320;
export const WORLD_SCALE = 22.0;

export function geoToXZ(lat, lon) {
  const x = (lon - LON0) * 73.15 * WORLD_SCALE;
  const z = -(lat - LAT0) * 111.2 * WORLD_SCALE;
  return [Number(x.toFixed(2)), Number(z.toFixed(2))];
}

export const MONTMARTRE_HILL_XZ = geoToXZ(48.8867, 2.3410);
export const PANTHEON_HILL_XZ = geoToXZ(48.8462, 2.3464);
export const CHAILLOT_HILL_XZ = geoToXZ(48.8628, 2.2862);
export const BELLEVILLE_HILL_XZ = geoToXZ(48.8765, 2.3880);

// Terrain elevation helper (authentic Paris topography: Butte Montmartre 130m,
// Belleville/Buttes-Chaumont 128m, Colline de Chaillot/Trocadéro 67m,
// Montagne Sainte-Geneviève/Panthéon 61m)
export function getTerrainY(x, z) {
  let y = 0;
  const dMont = Math.hypot(x - MONTMARTRE_HILL_XZ[0], z - MONTMARTRE_HILL_XZ[1]);
  if (dMont < 23.0) {
    const t = Math.max(0, 1 - dMont / 23.0);
    y = Math.max(y, t * t * (3 - 2 * t) * 5.2);
  }
  const dPan = Math.hypot(x - PANTHEON_HILL_XZ[0], z - PANTHEON_HILL_XZ[1]);
  if (dPan < 16.0) {
    const t = Math.max(0, 1 - dPan / 16.0);
    y = Math.max(y, t * t * (3 - 2 * t) * 1.55);
  }
  const dChail = Math.hypot(x - CHAILLOT_HILL_XZ[0], z - CHAILLOT_HILL_XZ[1]);
  if (dChail < 11.5) {
    const t = Math.max(0, 1 - dChail / 11.5);
    y = Math.max(y, t * t * (3 - 2 * t) * 1.15);
  }
  const dBell = Math.hypot(x - BELLEVILLE_HILL_XZ[0], z - BELLEVILLE_HILL_XZ[1]);
  if (dBell < 26.0) {
    const t = Math.max(0, 1 - dBell / 26.0);
    y = Math.max(y, t * t * (3 - 2 * t) * 4.4);
  }
  return y;
}

